import type { RelationMap } from "../src/scoped/relation-types.ts";
import { readSchemaModels } from "./read-schema.ts";

/** Every relation field of every model, from `prisma/schema/*.prisma` (ADR 0113). */
export function buildRelationMap(): RelationMap {
  const models = readSchemaModels();
  const names = new Set(models.map((model) => model.name));
  const map: Record<string, Record<string, { target: string; list: boolean }>> = {};
  for (const model of [...models].sort((a, b) => a.name.localeCompare(b.name))) {
    const fields: Record<string, { target: string; list: boolean }> = {};
    for (const field of model.fields) {
      const target = field.type.replace(/[[\]?]/g, "");
      if (!names.has(target)) continue;
      fields[field.name] = { target, list: field.type.endsWith("[]") };
    }
    if (Object.keys(fields).length > 0) map[model.name] = fields;
  }
  return map;
}

/** The generated module's source, kept in step by `test/relation-map.test.ts`. */
export function relationMapSource(): string {
  const body = JSON.stringify(buildRelationMap(), null, 2);
  return [
    "// Generated by `pnpm --filter @bibi/db gen:relations` from prisma/schema (ADR 0113). Do not edit.",
    'import type { RelationMap } from "./relation-types";',
    "",
    `export const RELATIONS: RelationMap = ${body};`,
    "",
  ].join("\n");
}
