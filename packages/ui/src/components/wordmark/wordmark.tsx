/** SVG Wordmark component for the "Bibi" brand with scalable sizing. */
export function Wordmark({
  className,
  size = "md",
  label = "Bibi",
  style,
  ...props
}: WordmarkProps) {
  const isPreset = typeof size === "string" && PRESET_NAMES.has(size);
  const variantSize = isPreset ? (size as WordmarkPresetSize) : "custom";
  const customStyle: CSSProperties | undefined = !isPreset
    ? {
        height: typeof size === "number" ? `${size}px` : size,
        width: "auto",
        ...style,
      }
    : style;

  return (
    <svg
      role="img"
      data-slot="wordmark"
      aria-label={label}
      viewBox="0 0 189 125"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={cn(wordmarkVariants({ size: variantSize }), className)}
      style={customStyle}
      {...props}
    >
      <title>{label}</title>
      <WordmarkGlyphs />
    </svg>
  );
}
